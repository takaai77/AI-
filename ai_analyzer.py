def analyze_with_claude(api_key, frames, prompt):
    """Claude APIで分析"""
    client = anthropic.Anthropic(api_key=api_key)

    # コンテンツ構築
    content = [{"type": "text", "text": prompt}]

    # フレーム追加
    for frame in frames:
        if frame.startswith('data:image'):
            base64_data = frame.split(',')[1]
        else:
            base64_data = frame

        content.append({
            "type": "image",
            "source": {
                "type": "base64",
                "media_type": "image/jpeg",
                "data": base64_data
            }
        })

    # API呼び出し
    message = client.messages.create(
        model=CLAUDE_MODEL,
        max_tokens=MAX_TOKENS,
        messages=[{
            "role": "user",
            "content": content
        }]
    )

    return message.content[0].text


def analyze_with_gemini(api_key, frames, prompt):
    """Gemini APIで分析"""
    genai.configure(api_key=api_key)
    model = genai.GenerativeModel(GEMINI_MODEL)

    # コンテンツ構築
    parts = [prompt]

    for frame in frames:
        if frame.startswith('data:image'):
            base64_data = frame.split(',')[1]
        else:
            base64_data = frame

        parts.append({
            "inline_data": {
                "mime_type": "image/jpeg",
                "data": base64_data
            }
        })

    # API呼び出し
    response = model.generate_content(
        parts,
        generation_config={
            "temperature": 0.7,
            "max_output_tokens": MAX_TOKENS,
        }
    )

    return response.text


def analyze_video(api_key, ai_provider, frames, analysis_type, video_url, video_title, additional_notes=""):
    """動画を分析"""
    try:
        # プロンプト生成
        prompt = generate_analysis_prompt(analysis_type, video_url, video_title, additional_notes)

        # AI分析
        if ai_provider == "claude":
            result = analyze_with_claude(api_key, frames, prompt)
        elif ai_provider == "gemini":
            result = analyze_with_gemini(api_key, frames, prompt)
        else:
            raise ValueError(f"Unknown AI provider: {ai_provider}")

        return {
            'success': True,
            'result': result
        }

    except Exception as e:
        print(f"分析エラー: {e}")
        return {
            'success': False,
            'error': str(e),
            'result': None
        }


